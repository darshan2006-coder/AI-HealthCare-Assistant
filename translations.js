// Language Engine Logic

function setLanguage(lang) {
    const selectedLang = translations[lang] ? lang : 'en';
    const dict = translations[selectedLang];

    localStorage.setItem('preferredLanguage', selectedLang);
    document.documentElement.lang = selectedLang;

    // 1. Text elements
    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const key = element.getAttribute('data-i18n');
        if (dict[key]) {
            if (element.tagName === 'TITLE') {
                document.title = dict[key];
            } else {
                element.textContent = dict[key];
            }
        }
    });

    // 2. Placeholder inputs
    document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            element.placeholder = dict[key];
        }
    });

    // 3. Titles and tooltips
    document.querySelectorAll('[data-i18n-title]').forEach((element) => {
        const key = element.getAttribute('data-i18n-title');
        if (dict[key]) {
            element.title = dict[key];
        }
    });

    // Synchronize selector dropdown
    const langSelect = document.getElementById('languageSelect');
    if (langSelect) {
        langSelect.value = selectedLang;
    }
}

function getCurrentLanguage() {
    return localStorage.getItem('preferredLanguage') || 'en';
}

// Helper to fetch translations inside JS scripts (For Chat Bot Messages)
function t(key) {
    const lang = getCurrentLanguage();
    return (translations[lang] && translations[lang][key]) 
        ? translations[lang][key] 
        : (translations['en'][key] || key);
}

document.addEventListener('DOMContentLoaded', () => {
    const activeLang = getCurrentLanguage();
    setLanguage(activeLang);

    const langSelect = document.getElementById('languageSelect');
    if (langSelect) {
        langSelect.addEventListener('change', (e) => {
            setLanguage(e.target.value);
        });
    }
});